    void reset() {
        autoId();
        tId.setEditable(false);
        tNama.setText(null);
        tPrice.setText(null);
        tDeskripsi.setText(null);
        cCategory.setSelectedItem(null);
    }
    
    void autoId() {
        try {
            product prdId = new product();
            ResultSet rs = prdId.autoId();
            
            if (rs.next()) {
                int id = rs.getInt("Id") + 1;
                tId.setText(String.valueOf(id));
            }else {
                tId.setText("1");
            }
        } catch (SQLException sQLException) {
            JOptionPane.showMessageDialog(null, "EROR :" + sQLException.getMessage());
        }
    }
    
    void ComboBox() {
        try {
            category value = new category();
            ResultSet rs = value.dataComboBox();
            
            while (rs.next()) {
                String data = rs.getString("CategoryName");
                cCategory.addItem(data);
                
            }
        } catch (SQLException sQLException) {
            JOptionPane.showMessageDialog(null, " EROR : " + sQLException.getMessage());
        }
    }
    
    void load_table() {
        DefaultTableModel model = new DefaultTableModel();
        product prd = new product();

    // Tambahkan kolom
        model.addColumn("Id");
        model.addColumn("Nama");
        model.addColumn("Category");
        model.addColumn("Description");
        model.addColumn("Price");

    // Ambil data dari method TampilProduct
        ResultSet rs = prd.TampilProduct();

        try {
            while (rs.next()) {
                int id = rs.getInt("productId");
                String name = rs.getString("productName");
                String category = rs.getString("categoryName");
                String description = rs.getString("productDescription");
                int price = rs.getInt("productPrice");

                // Gunakan kurung kurawal untuk membuat array
                Object[] data = {id, name, category, description, price};
                model.addRow(data);
        }
        } catch (SQLException sQLException) {
            System.out.println("Error :" + sQLException.getMessage());
        }
        tblProduct.setModel(model);
    }

