    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        // TODO add your handling code here:
        product prd = new product();
        category ctg = new category();
        
        try {
            prd.setProductName(tNama.getText());
            prd.setProductDescription(tDeskripsi.getText());
            prd.setProductPrice(Integer.parseInt(tPrice.getText()));
            
            ctg.setCategoryName(cCategory.getSelectedItem().toString());
            ResultSet rs = ctg.konversi();
            
            if (rs != null && rs.next()) {
                int Id = rs.getInt("categoryId");
                prd.setProductCategory(Id);
                
                prd.TambahProduct();
            } else {
                JOptionPane.showMessageDialog(null, "Produk Berhasil DiTambah");
            }
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Harga Harus Berupa Angka");
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Eror SQL : " + e.getMessage());
        }
        
        load_table();
        reset();
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        product prd = new product();
        category ctg = new category();
        
        try {
            prd.setProductName(tNama.getText());
            prd.setProductDescription(tDeskripsi.getText());
            prd.setProductPrice(Integer.parseInt(tPrice.getText()));
            
            ctg.setCategoryName(cCategory.getSelectedItem().toString());
            ResultSet rs = ctg.konversi();
            
            if (rs.next()) {
                int id = rs.getInt("categoryId");
                prd.setProductCategory(id);
            }
            prd.UbahProduct();
            
        } catch (NumberFormatException numberFormatException) {
            JOptionPane.showMessageDialog(null, "Eror : " + numberFormatException.getMessage());
        } catch (SQLException sQLException) {
            JOptionPane.showMessageDialog(null, "Eror : " + sQLException.getMessage());
        }
        load_table();
        reset();
    }//GEN-LAST:event_btnUbahActionPerformed

