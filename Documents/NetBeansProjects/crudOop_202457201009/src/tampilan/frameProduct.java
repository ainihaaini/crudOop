    private void tblProductMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductMouseClicked
        // TODO add your handling code here:
        int row = tblProduct.getSelectedRow();
        
        if (row != -1) {
            String id = tblProduct.getValueAt(row, 0).toString();
            String name = tblProduct.getValueAt(row, 1).toString();
            String category = tblProduct.getValueAt(row, 2).toString();
            String description = tblProduct.getValueAt(row, 3).toString();
            String price = tblProduct.getValueAt(row, 4).toString();
            
            tId.setText(id);
            tNama.setText(name);
            tDeskripsi.setText(description);
            tPrice.setText(price);
            cCategory.setSelectedItem(category);
        }
        
    }//GEN-LAST:event_tblProductMouseClicked

